NSString *GTokTranslate(NSString *text)
{

    if(!text ||
       text.length == 0)
        return nil;



    NSString *clean =
    [[text stringByReplacingOccurrencesOfString:@"\u200B"
                                     withString:@""]
     stringByTrimmingCharactersInSet:
     [NSCharacterSet whitespaceAndNewlineCharacterSet]];



    NSString *result =
    GTokTable()[clean];



    if(result)
        return result;




    /*
     长文本前缀匹配
     */


    for(NSString *key in GTokTable())
    {

        if([clean hasPrefix:key])
        {

            return
            [clean stringByReplacingOccurrencesOfString:key
                                             withString:
             GTokTable()[key]];

        }

    }




    return nil;

}
